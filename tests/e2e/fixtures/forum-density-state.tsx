export function useQuery<Ref extends FunctionReference<"query">>(
  ref: Ref,
  args: FunctionArgs<Ref> | "skip",
) {
  const name = getFunctionName(ref);
  const key = JSON.stringify(args);
  // Model Convex subscription admissions, not repeated hook evaluations.
  // Stable query arguments remain subscribed across a presentation rerender.
  useEffect(() => {
    if (key !== JSON.stringify("skip"))
      evidence.backendReads.push(`${name}:${key}`);
  }, [name, key]);
  if (name === "forum:getMyForumNavState") return nav;
  if (name === "forum:overview") return overview;
  if (name === "forum:feedAuthorizationFingerprint")
    return { fingerprint: "density-owner" };
  if (name === "forum:getMyForumExperience")
    return { defaultFeed: "discover", authorFilter: "all" };
  return terminal.useQuery(ref, args);
}
