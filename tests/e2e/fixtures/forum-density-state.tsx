export function useMutation(ref: FunctionReference<"mutation">) {
  const name = getFunctionName(ref);
  return useCallback(async () => {
    evidence.mutations.push(name);
    if (
      name !== "forum:recordForumExperienceEvent" &&
      name !== "forumSwapRecovery:ensure"
    ) {
      evidence.forbidden.push(name);
      throw Error(`Writes denied: ${name}`);
    }
  }, [name]);
}
