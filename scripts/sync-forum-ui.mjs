import { readFile, writeFile } from "node:fs/promises";

// CSS is imported normally by Next.js and bundled as text for sandboxed MCP hosts.
// No network fetch or additional CSP origin is needed by the embedded app.
const source = new URL("../styles/forum-shared.css", import.meta.url);
const target = new URL("../lib/forum-shared-css.generated.ts", import.meta.url);
const css = await readFile(source, "utf8");
if (/<\/style/i.test(css)) throw new Error("Shared forum CSS cannot contain a closing style tag.");
const font = await readFile(new URL("../public/fonts/Geist-Latin.woff2", import.meta.url));
const fontCss = `@font-face{font-family:Geist;font-style:normal;font-weight:100 900;font-display:swap;src:url(data:font/woff2;base64,${font.toString("base64")}) format("woff2");}`;
const generated = `// Generated by scripts/sync-forum-ui.mjs. Edit styles/forum-shared.css.\nexport const FORUM_SHARED_CSS = ${JSON.stringify(css)};\nexport const FORUM_PLUGIN_FONT_CSS = ${JSON.stringify(fontCss)};\n`;
if (process.argv.includes("--check")) {
  const current = await readFile(target, "utf8").catch(() => "");
  if (current !== generated) throw new Error("Forum UI bundle is stale. Run bun run ui:sync.");
} else {
  await writeFile(target, generated);
}
